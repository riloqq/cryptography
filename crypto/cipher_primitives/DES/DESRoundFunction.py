    P = [16, 7, 20, 21, 29, 12, 28, 17, 1, 15, 23, 26, 5, 18, 31, 10, 2, 8, 24, 14, 32, 27, 3, 9, 19, 13, 30, 6, 22, 11, 4, 25]

    def apply(self, right_half: bytes, round_key: bytes) -> bytes:
        if len(right_half) != 4:
            raise ValueError("Right half must be 4 bytes")
        expanded = bitperm(right_half, self.E, msb_first=True, one_based_indexing=True)
        xored = xor_bytes(expanded, round_key)
        substituted = self._process_sboxes(xored)
        permuted = bitperm(substituted, self.P, msb_first=True, one_based_indexing=True)
        return permuted

    def _process_sboxes(self, input_data: bytes) -> bytes:
        if len(input_data) != 6:
            raise ValueError("Input must be 6 bytes")
        bits_val = int.from_bytes(input_data, "big")
        output_val = 0
        for box_idx in range(8):
            box_input = (bits_val >> (42 - box_idx * 6)) & 0b111111
            row_val = ((box_input & 0b100000) >> 4) | (box_input & 0b000001)
            col_val = (box_input >> 1) & 0b1111
            box_output = self.SBOXES[box_idx][row_val][col_val]
            output_val = (output_val << 4) | box_output
        return output_val.to_bytes(4, "big")